namespace FishPuzzle.Bubbles
{
    /// <summary>
    /// Bubble modifiers. Standard bubbles use None. Frozen is played since M15. Locked and Other are reserved.
    /// </summary>
    public enum BubbleModifier
    {
        None = 0,
        Frozen = 1,
        Locked = 2,
        Other = 3
    }
}
